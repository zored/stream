import sys
import urllib.request

URL = "https://unicode.org/Public/emoji/15.1/emoji-test.txt"
ORDER = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Activities",
         "Travel & Places", "Objects", "Symbols", "Flags"]
TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}

groups, group = {}, None
for line in urllib.request.urlopen(URL).read().decode().splitlines():
    if line.startswith("# group: "):
        group = line[9:]
        continue
    if not line or line.startswith("#") or "; fully-qualified" not in line:
        continue
    char = line.split("# ", 1)[1].split(" ", 1)[0]
    if not TONES & set(char):
        groups.setdefault(group, []).append(char)

out = ["// Code generated by tools/gen_emoji.py from " + URL + ". DO NOT EDIT.", "", "package main", "",
       "var emojiGroups = [][]string{"]
for name in ORDER:
    out.append(f"\t{{{', '.join(repr(c).replace(chr(39), chr(34)) for c in groups[name])}}},")
out.append("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
